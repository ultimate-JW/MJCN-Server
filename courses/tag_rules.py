def infer_tags(course):
    """Course → 추론된 태그 set.

    학과 default + 과목명 키워드 매칭 합집합. 매칭 없으면 빈 set.
    호출자는 set을 list로 변환해 Course.tags에 박는다.
    """
    tags = set()
    if course.major and course.major in MAJOR_DEFAULT_TAGS:
        tags.update(MAJOR_DEFAULT_TAGS[course.major])
    name = course.name or ''
    for keyword, tag_list in NAME_KEYWORD_TAGS:
        if keyword in name:
            tags.update(tag_list)
    return tags
